<script>
(function() {
    "use strict";
    var track    = document.getElementById("testimonialsTrack");
    var carousel = document.getElementById("testimonialsCarousel");
    var dotsEl   = document.getElementById("testimonialsDots");
    var prevBtn  = document.getElementById("testimonialsPrev");
    var nextBtn  = document.getElementById("testimonialsNext");
    if (!track || !carousel || !dotsEl) return;

    var slides    = Array.from(track.children);
    var count     = slides.length;
    var current   = 0;
    var timer     = null;
    var paused    = false;
    var animating = false;

    track.addEventListener("transitionend", function() { animating = false; });

    function sw() { return carousel.offsetWidth; }

    function goTo(idx) {
        if (animating) return;
        if (idx < 0) idx = count - 1;
        if (idx >= count) idx = 0;
        current = idx;
        animating = true;
        track.style.transform = "translateX(" + (-current * sw()) + "px)";
        updateDots();
        setTimeout(function() { animating = false; }, 600);
    }

    function updateDots() {
        var dots = dotsEl.querySelectorAll(".enzo-testimonial-dot");
        dots.forEach(function(d, i) {
            d.classList.toggle("active", i === current);
            d.setAttribute("aria-selected", i === current ? "true" : "false");
        });
    }

    function buildDots() {
        dotsEl.innerHTML = "";
        for (var i = 0; i < count; i++) {
            var btn = document.createElement("button");
            btn.className = "enzo-testimonial-dot" + (i === 0 ? " active" : "");
            btn.setAttribute("type", "button");
            btn.setAttribute("role", "tab");
            btn.setAttribute("aria-label", "Go to testimonial " + (i + 1));
            btn.setAttribute("aria-selected", i === 0 ? "true" : "false");
            btn.addEventListener("click", function(idx) { return function() { goTo(idx); resetTimer(); }; }(i));
            dotsEl.appendChild(btn);
        }
    }

    /* ---- autoplay ---- */
    function startTimer() {
        stopTimer();
        timer = setInterval(function() {
            if (paused) return;
            goTo(current + 1);
        }, 5000);
    }
    function stopTimer() { clearInterval(timer); }
    function resetTimer() { stopTimer(); startTimer(); }

    /* ---- arrows ---- */
    if (prevBtn) prevBtn.addEventListener("click", function() { goTo(current - 1); resetTimer(); });
    if (nextBtn) nextBtn.addEventListener("click", function() { goTo(current + 1); resetTimer(); });

    /* ---- hover pause ---- */
    carousel.addEventListener("mouseenter", function() { paused = true; });
    carousel.addEventListener("mouseleave", function() { paused = false; });

    /* ---- swipe ---- */
    var sx = 0;
    carousel.addEventListener("touchstart", function(e) {
        var t = e.changedTouches[0];
        sx = t.clientX;
        track.style.transition = "none";
        animating = false;
    }, { passive: true });

    carousel.addEventListener("touchmove", function(e) {
        e.preventDefault();
        var t = e.changedTouches[0];
        track.style.transform = "translateX(" + (-current * sw() + (t.clientX - sx)) + "px)";
    }, { passive: false });

    carousel.addEventListener("touchend", function(e) {
        track.style.transition = "";
        var diff = e.changedTouches[0].clientX - sx;
        var threshold = sw() * 0.15;
        if (Math.abs(diff) > threshold) {
            if (diff < 0) goTo(current + 1);
            else goTo(current - 1);
        } else {
            goTo(current);
        }
        resetTimer();
    }, { passive: true });

    /* ---- resize ---- */
    var rt;
    window.addEventListener("resize", function() {
        clearTimeout(rt);
        rt = setTimeout(function() { animating = false; goTo(current); }, 150);
    });

    /* ---- init ---- */
    buildDots();
    goTo(0);
    startTimer();
})();
</script>
